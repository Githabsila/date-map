def _offset(name: str, lat: float, lon: float, radius_m: int) -> tuple[float, float]:
    """Детерминированная точка в радиусе от центра: одно и то же место всегда на одном месте."""
    h = hashlib.md5(name.encode()).digest()
    angle = h[0] / 255 * 2 * math.pi
    dist = (0.15 + h[1] / 255 * 0.75) * min(radius_m, 6000)
    dlat = dist * math.cos(angle) / 111_000
    dlon = dist * math.sin(angle) / (111_000 * math.cos(math.radians(lat)))
    return lat + dlat, lon + dlon


def _matches(query: str, keywords: str) -> int:
    words = [w for w in query.lower().replace("-", " ").split() if len(w) >= 3]
    return sum(1 for w in words for k in keywords.split() if w.startswith(k) or k.startswith(w[:5]))


async def search(query: str, lat: float, lon: float, radius_m: int, client: httpx.AsyncClient) -> list[Place]:
    scored = [(_matches(query, item[2]), item) for item in CATALOG]
    found = [item for score, item in sorted(scored, key=lambda s: -s[0]) if score > 0][:8]
    places = []
    for name, kind, _, check, rating, reviews in found:
        plat, plon = _offset(name, lat, lon, radius_m)
        places.append(Place(
            name=name, lat=plat, lon=plon,
            address="Демо-адрес",
            kind=kind,
            rating=rating, reviews=reviews,
            avg_check=check or None,
            price_level=price_level_from_check(check) if check else None,
            sources=[Source(provider="demo", url="", rating=rating, reviews=reviews)],
        ))
    return places
